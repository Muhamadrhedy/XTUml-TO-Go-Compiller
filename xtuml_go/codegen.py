"""Go source generation from the validated intermediate representation."""
import re
from .model import Model, UMLClass
from .semantic import go_type, exported, private

def safe_go_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'

def generate(model: Model, package_name: str = "main") -> str:
    if not re.match(r"^[a-z][a-z0-9_]*$", package_name):
        raise ValueError("Nama package Go harus dimulai huruf kecil dan hanya berisi huruf kecil, angka, atau underscore.")
    needs_time = any(
        go_type(a.type_name) == "time.Time" for c in model.classes for a in c.attributes
    ) or any(
        (o.return_type and go_type(o.return_type) == "time.Time") or any(go_type(p.type_name) == "time.Time" for p in o.params)
        for c in model.classes for o in c.operations
    )
    lines = [f"package {package_name}", ""]
    if needs_time:
        lines += ['import "time"', ""]
    lines += ["// Code generated by xtUML to Go Compiler.", "// Review TODO comments and custom types before compiling.", ""]
    for cls in model.classes:
        associations = [a for a in model.associations if a.source == cls.name]
        lines.extend(generate_class(cls, associations))
    return "\n".join(lines).rstrip() + "\n"

def generate_class(cls: UMLClass, associations=None) -> list[str]:
    associations = associations or []
    name = exported(cls.name)
    lines = [f"type {name} struct {{"]
    if cls.parent:
        lines.append(f"\t{exported(cls.parent)}")
    if cls.attributes:
        for a in cls.attributes:
            field = exported(a.name) if a.visibility == "+" else private(a.name)
            lines.append(f"\t{field} {go_type(a.type_name)}")
    else:
        lines.append("\t// TODO: add fields from the UML model.")
    for assoc in associations:
        field = exported(assoc.field_name)
        target = exported(assoc.target)
        field_type = f"[]{target}" if assoc.multiplicity == "many" else (f"*{target}" if assoc.multiplicity == "optional" else target)
        lines.append(f"\t{field} {field_type}")
    if cls.state_machine:
        lines.append(f"\t{private(cls.state_machine.name)}State {exported(cls.state_machine.name)}State")
    lines += ["}", ""]
    params = ", ".join(f"{private(a.name)} {go_type(a.type_name)}" for a in cls.attributes)
    lines += [f"func New{name}({params}) *{name} {{", f"\treturn &{name}{{"]
    for a in cls.attributes:
        field = exported(a.name) if a.visibility == "+" else private(a.name)
        lines.append(f"\t\t{field}: {private(a.name)},")
    for assoc in associations:
        if assoc.multiplicity == "many":
            lines.append(f"\t\t{exported(assoc.field_name)}: make([]{exported(assoc.target)}, 0),")
    if cls.state_machine:
        sm = cls.state_machine
        lines.append(f"\t\t{private(sm.name)}State: {exported(sm.name)}{exported(sm.initial)},")
    lines += ["\t}", "}", ""]
    for op in cls.operations:
        method_name = exported(op.name) if op.visibility == "+" else private(op.name)
        params = ", ".join(f"{private(p.name)} {go_type(p.type_name)}" for p in op.params)
        ret = f" {go_type(op.return_type)}" if op.return_type else ""
        lines.append(f"func (self *{name}) {method_name}({params}){ret} {{")
        lines.append("\t// TODO: implement the operation's behavior.")
        if op.return_type:
            rt = go_type(op.return_type)
            lines += [f"\tvar result {rt}", "\treturn result"]
        lines += ["}", ""]
    if cls.state_machine:
        lines.extend(generate_state_machine(cls))
    return lines

def generate_state_machine(cls: UMLClass) -> list[str]:
    sm = cls.state_machine
    owner = exported(cls.name)
    machine = exported(sm.name)
    enum_name = f"{machine}State"
    state_field = f"{private(sm.name)}State"
    lines = [f"// {enum_name} represents the states in {sm.name}.",
             f"type {enum_name} string", "", "const ("]
    for state in sm.states:
        lines.append(f'\t{machine}{exported(state.name)} {enum_name} = {safe_go_string(state.name)}')
    lines += [")", "", f"// Current{machine}State returns the current state.", f"func (self *{owner}) Current{machine}State() {enum_name} {{",
              f"\treturn self.{state_field}", "}", ""]
    lines += [f"// Handle{machine}Event applies a valid event transition.", f"func (self *{owner}) Handle{machine}Event(event string) bool {{",
              f"\tcurrent := self.Current{machine}State()", "\tswitch current {"]
    for state in sm.states:
        outgoing = [t for t in sm.transitions if t.source == state.name]
        if not outgoing: continue
        lines.append(f"\tcase {machine}{exported(state.name)}:")
        lines.append("\t\tswitch event {")
        for tr in outgoing:
            lines.append(f'\t\tcase {safe_go_string(tr.event)}:')
            if tr.action:
                lines.append(f"\t\t\t// TODO: invoke action {tr.action}.")
            lines.append(f"\t\t\tself.{state_field} = {machine}{exported(tr.target)}")
            lines.append("\t\t\treturn true")
        lines += ["\t\t}", "\t\treturn false"]
    lines += ["\tdefault:", "\t\treturn false", "\t}", "}", ""]
    return lines
